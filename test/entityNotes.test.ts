import { describe, it, expect } from "vitest";
import { buildCorridorStubMarkdown, corridorNotePathFor, noteHoverExcerpt } from "../src/entityNotes";
import { buildDoorNoteMarkdown, type DoorNoteParams } from "../src/doorNotes";
import { DEFAULT_LOCK_TRAP_RULES } from "../src/lockTrapRules";
import type { DungeonDoor } from "../src/dungeonData";

describe("corridorNotePathFor", () => {
  it("builds the Corridors-folder path under the floor's own folder", () => {
    expect(corridorNotePathFor("Dungeons/My Dungeon/", "Floor 1", 5)).toBe(
      "Dungeons/My Dungeon/Floor 1/Corridors/Corridor 5.md"
    );
  });

  it("works at vault root (empty folder prefix)", () => {
    expect(corridorNotePathFor("", "Floor 1", 0)).toBe("Floor 1/Corridors/Corridor 0.md");
  });
});

describe("buildCorridorStubMarkdown", () => {
  it("includes the corridor id and a free-text Notes section", () => {
    const md = buildCorridorStubMarkdown(5);
    expect(md).toContain("Corridor 5");
    expect(md).toContain("## Notes");
  });
});

function makeDoor(overrides: Partial<DungeonDoor> = {}): DungeonDoor {
  return {
    id: 3,
    connects: [
      { kind: "room", id: 7 },
      { kind: "corridor", id: 0 },
    ],
    cellA: [1, 5, 0],
    cellB: [1, 7, 0],
    material: "wood",
    secret: false,
    width: 1,
    locked: false,
    trapped: false,
    stuck: false,
    ...overrides,
  };
}

function makeDoorNoteParams(overrides: Partial<DoorNoteParams> = {}): DoorNoteParams {
  return {
    door: makeDoor({ locked: true }),
    floorBasename: "Floor 1",
    challengeLevel: 3,
    floorLevel: 1,
    rules: DEFAULT_LOCK_TRAP_RULES,
    trapFlavor: null,
    lockRoll: { dc: 27, roll: 6 },
    ...overrides,
  };
}

describe("noteHoverExcerpt", () => {
  it("keeps a locked door's Locked line, stripping the boilerplate header/instructions/markdown emphasis", () => {
    const md = buildDoorNoteMarkdown(makeDoorNoteParams());
    const excerpt = noteHoverExcerpt(md);
    expect(excerpt).toContain("Locked: Open Lock DC 27 (floor Level 1 + 20 + 6 on 1d10)");
    expect(excerpt).not.toContain("Auto-generated by");
    expect(excerpt).not.toContain("Door 3 —");
    expect(excerpt).not.toContain("Hand-added detail");
    expect(excerpt).not.toContain("**");
  });

  it("keeps a trapped door's flavor text too", () => {
    const md = buildDoorNoteMarkdown(
      makeDoorNoteParams({
        door: makeDoor({ trapped: true }),
        trapFlavor: { name: "Poison Dart Trap", description: "a dart fires from the wall" },
      })
    );
    const excerpt = noteHoverExcerpt(md);
    expect(excerpt).toContain("Poison Dart Trap");
  });

  it("returns \"\" for an unedited corridor stub (pure boilerplate)", () => {
    expect(noteHoverExcerpt(buildCorridorStubMarkdown(5))).toBe("");
  });

  it("surfaces hand-added text under a corridor stub's Notes section once someone's actually written something", () => {
    const md = buildCorridorStubMarkdown(5) + "A hidden lever behind the tapestry opens a passage north.";
    expect(noteHoverExcerpt(md)).toBe("A hidden lever behind the tapestry opens a passage north.");
  });

  it("caps long excerpts and appends an ellipsis", () => {
    const longLine = "x".repeat(300);
    const excerpt = noteHoverExcerpt(`Corridor 9\n\n${longLine}`, 50);
    expect(excerpt.length).toBe(50);
    expect(excerpt.endsWith("…")).toBe(true);
  });
});
